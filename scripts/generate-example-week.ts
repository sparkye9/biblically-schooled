/**
 * Writes docs/EXAMPLE-WEEK.md: one complete week exactly as the engine
 * generates it for the default family (profiles, schedule, worksheets).
 * Run: npm run docs:example-week [-- <week>]
 */
import { writeFileSync } from 'node:fs'
import { getBibleWeek } from '../lib/curriculum/bible'
import { ACTIVITY_LABELS, DAY_RHYTHM, LESSON_DAYS, type LessonDay } from '../lib/curriculum/types'
import { buildDayPlan, type ChildPlan, type PlanItem } from '../lib/plan/day-plan'
import { DEFAULT_SCHEDULE, ENRICHMENT_LABELS, WEEKDAY_LABELS, enrichmentsOf, indexOf } from '../lib/plan/schedule'
import { initialState } from '../lib/state/defaults'
import * as L from '../lib/state/logic'
import { getWorksheet } from '../lib/worksheets'

const week = Number(process.argv[2]) || 12
const s = initialState(new Date(2026, 10, 9))
const learners = s.children.map((c) => L.learnerOf(c, s))
const weekdays = [1, 2, 4, 5] // Mon, Tue, Thu, Fri
const b = getBibleWeek(week)
const out: string[] = []
const SUBJ: Record<string, string> = { bible: 'Bible', literacy: 'Literacy', math: 'Math', handwriting: 'Handwriting', language: 'Language', enrichment: 'Enrichment', 'read-aloud': 'Read-aloud' }

out.push(`# Example week: Week ${week} — ${b.title}`, '')
out.push('_Generated by `npm run docs:example-week` from the curriculum engine with the default family profiles and calendar (Standard Day). This is exactly what the app shows._', '')
out.push(`Bible: ${b.passage} · Memory verse ${b.verse.ref}: “${b.verse.text}” (KJV)`, '')
out.push('Wednesday is co-op (church 9–12, no lesson packet).', '')

const paper = new Map<string, number>()
const line = (it: PlanItem) => {
  const l = it.lesson
  const prints = l?.worksheet && getWorksheet(l.worksheet.id)
  return `**${SUBJ[it.subject]}** (${it.minutes} min · ${ACTIVITY_LABELS[it.activity]}${prints ? ` · 🖨 prints “${prints.title}” — ${prints.activity}` : ' · nothing to print'}): ${it.title}`
}

LESSON_DAYS.forEach((day: LessonDay, i) => {
  const wd = weekdays[i]
  const sched = DEFAULT_SCHEDULE[wd]
  const plan = buildDayPlan({ index: indexOf(week, day), mode: 'standard', easy: false, learners, enrichment: enrichmentsOf(sched), date: new Date(2026, 10, 9 + i), useSeasonal: false })
  out.push(`## ${WEEKDAY_LABELS[wd]} — ${DAY_RHYTHM[day].name}`, '')
  out.push(`_${DAY_RHYTHM[day].summary}_${sched.note ? ` ${sched.note}` : ''}`, '')
  out.push(`About ${plan.estimate.totalMinutes} minutes. Enrichment: ${enrichmentsOf(sched).map((k) => ENRICHMENT_LABELS[k]).join(' + ') || 'none'}.`, '')
  const bible = plan.children[0].items.find((x) => x.subject === 'bible')!
  out.push(`### Everyone together`, '', `- ${line(bible)}`, `  - ${bible.lesson!.guide.teach[0]}`, `  - ${bible.lesson!.guide.practice.join(' ')}`)
  for (const e of plan.enrichments) if (e.activity) out.push(`- **${e.label}** (optional): ${e.activity.title} — ${e.activity.steps[0]}`)
  out.push('')
  const seen = new Set<string>()
  for (const c of plan.children as ChildPlan[]) {
    const sig = c.items.filter((x) => x.lesson && x.subject !== 'bible').map((x) => x.lesson!.id + (x.lesson!.guide.supports ? '+' : '')).join()
    if (seen.has(sig)) continue
    seen.add(sig)
    const names = plan.children.filter((o) => o.items.filter((x) => x.lesson && x.subject !== 'bible').map((x) => x.lesson!.id + (x.lesson!.guide.supports ? '+' : '')).join() === sig).map((o) => o.learner.name)
    out.push(`### ${names.join(' & ')}`, '')
    for (const it of c.items.filter((x) => x.lesson && x.subject !== 'bible')) {
      const g = it.lesson!.guide
      if (it.lesson!.worksheet) for (const n of names) paper.set(n, (paper.get(n) ?? 0) + 1)
      out.push(`- ${line(it)}`)
      out.push(`  - Objective: ${g.objective}`)
      if (g.warmUp) out.push(`  - Warm-up: ${g.warmUp}`)
      if (g.what) out.push(`  - What: ${g.what}`, `  - Why: ${g.why}`)
      if (g.how && day === 0) out.push(`  - How: ${g.how.join(' → ')}`)
      if (g.example && day === 0) out.push(`  - Say it: ${g.example}`)
      if (g.stages) out.push(`  - Stage: ${g.stages.map((st) => `${st.label} — ${st.text}`).join(' · ')}`)
      out.push(`  - Teach: ${g.teach.join(' / ')}`)
      out.push(`  - Practice: ${g.practice.join(' / ')}`)
      out.push(`  - Materials: ${g.materials.join(', ')}`)
      out.push(`  - Check: ${g.check}`)
      if (g.starters) out.push(`  - Sentence starters: ${g.starters.join(' · ')}`)
      if (g.structure && it.subject === 'math') out.push(`  - Structure: Beginning — ${g.structure.begin} Middle — ${g.structure.middle} End — ${g.structure.end}`)
      if (g.supports && it.subject !== 'language') out.push(`  - Access supports: ${g.supports.slice(3).join(' / ') || g.supports.join(' / ')}`)
    }
    out.push('')
  }
  out.push(`**How to run it:** ${plan.rotation.join(' ')}`, '')
})
out.push('## Pages printed this week', '')
for (const [n, k] of paper) out.push(`- ${n}: ${k} pages (Tuesday and Friday, plus a story page Thursday for readers)`)
out.push('')
writeFileSync('docs/EXAMPLE-WEEK.md', out.join('\n'))
console.log(`Wrote docs/EXAMPLE-WEEK.md (week ${week})`)
